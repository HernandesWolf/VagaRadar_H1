-- VagaRadar: esquema inicial (compatível com H2 em modo PostgreSQL e PostgreSQL 14+)

CREATE TABLE user_skills (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(80)  NOT NULL,
    normalized_name VARCHAR(80)  NOT NULL,
    skill_level     VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_user_skills_normalized UNIQUE (normalized_name)
);

CREATE TABLE job_opportunities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150)  NOT NULL,
    company     VARCHAR(120)  NOT NULL,
    location    VARCHAR(120),
    work_mode   VARCHAR(20)   NOT NULL,
    salary_min  NUMERIC(12, 2),
    salary_max  NUMERIC(12, 2),
    source_url  VARCHAR(500),
    description VARCHAR(5000),
    deadline    DATE,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL
);

CREATE INDEX idx_jobs_company  ON job_opportunities (company);
CREATE INDEX idx_jobs_deadline ON job_opportunities (deadline);

CREATE TABLE job_requirements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id          BIGINT      NOT NULL,
    name            VARCHAR(80) NOT NULL,
    normalized_name VARCHAR(80) NOT NULL,
    mandatory       BOOLEAN     NOT NULL,
    min_level       VARCHAR(20) NOT NULL,
    CONSTRAINT fk_requirement_job FOREIGN KEY (job_id) REFERENCES job_opportunities (id) ON DELETE CASCADE,
    CONSTRAINT uk_requirement_job_name UNIQUE (job_id, normalized_name)
);

CREATE INDEX idx_requirements_name ON job_requirements (normalized_name);

CREATE TABLE job_applications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id            BIGINT      NOT NULL,
    status            VARCHAR(20) NOT NULL,
    applied_at        DATE,
    follow_up_date    DATE,
    notes             VARCHAR(2000),
    status_changed_at TIMESTAMP   NOT NULL,
    created_at        TIMESTAMP   NOT NULL,
    CONSTRAINT fk_application_job FOREIGN KEY (job_id) REFERENCES job_opportunities (id) ON DELETE CASCADE,
    CONSTRAINT uk_application_job UNIQUE (job_id)
);

CREATE INDEX idx_applications_status ON job_applications (status);

CREATE TABLE selection_stages (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL,
    stage_type     VARCHAR(30)  NOT NULL,
    title          VARCHAR(120) NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    due_date       DATE,
    notes          VARCHAR(1000),
    sort_order     INT          NOT NULL,
    CONSTRAINT fk_stage_application FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);

CREATE TABLE interviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL,
    interview_type VARCHAR(20)  NOT NULL,
    scheduled_at   TIMESTAMP    NOT NULL,
    interviewer    VARCHAR(120),
    location       VARCHAR(255),
    status         VARCHAR(20)  NOT NULL,
    feedback       VARCHAR(2000),
    CONSTRAINT fk_interview_application FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);

CREATE INDEX idx_interviews_scheduled ON interviews (scheduled_at);

CREATE TABLE contacts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL,
    name           VARCHAR(120) NOT NULL,
    job_role       VARCHAR(120),
    email          VARCHAR(160),
    phone          VARCHAR(40),
    linkedin_url   VARCHAR(255),
    notes          VARCHAR(1000),
    CONSTRAINT fk_contact_application FOREIGN KEY (application_id) REFERENCES job_applications (id) ON DELETE CASCADE
);
